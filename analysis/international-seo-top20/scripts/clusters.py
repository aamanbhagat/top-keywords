def run():
    d=pd.read_csv(os.path.join(S,'master.csv'))
    out=[];memb=[]
    for cid,mk,name,inc,exc in C:
        x=d[(d.market==mk)&d.keyword.str.contains(inc,case=False,regex=True)]
        if exc: x=x[~x.keyword.str.contains(exc,case=False,regex=True)]
        v=x[x.vol_rank.notna()]
        top=v.sort_values('vol_rank',ascending=False).head(6)
        r=dict(id=cid,market=mk,concept=name,kw_in_csv=len(x),kw_in_screens=int(x.in_screenshot.sum()),kw_with_volume=len(v),
            n_10k=int((v.vol_rank>=4).sum()),n_1k=int((v.vol_rank==3).sum()),n_100=int((v.vol_rank==2).sum()),
            floor=int(sum(LB[int(k)] for k in v.vol_rank)),ceiling=int(sum(UB[int(k)] for k in v.vol_rank)),
            head=' | '.join(f'{t.keyword} ({t.vol})' for t in top.itertuples()),
            comp_mix='/'.join(f'{c}:{n}' for c,n in v.comp.fillna('?').value_counts().items()),
            max_bid_hi_inr=v.bid_hi.max() if len(v) else None)
        out.append(r)
        for t in x.itertuples(): memb.append(dict(cluster_id=cid,market=mk,keyword=t.keyword,vol=t.vol,comp=t.comp,yoy=t.yoy,m3=t.m3,bid_lo=t.bid_lo,bid_hi=t.bid_hi,in_screenshot=t.in_screenshot,validation_status=t.validation_status))
    o=pd.DataFrame(out); o.to_csv(os.path.join(S,'clusters.csv'),index=False)
    pd.DataFrame(memb).to_csv(os.path.join(S,'cluster_members.csv'),index=False)
    return o
